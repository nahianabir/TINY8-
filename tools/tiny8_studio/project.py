"""Tiny8 Studio — project manager.

A Tiny8 project is just a folder with:
  project.t8p        -- JSON config (name, board, fqbn, build command, etc.)
  src/               -- user C++ source files
  assets/            -- PBM source art
  generated/         -- output of the asset converter (PROGMEM headers)

This module is independent of tkinter; it just manipulates the project
files.  The GUI binds to it.
"""

from __future__ import annotations
import json
import os
import shutil
import subprocess
import sys
from dataclasses import asdict, dataclass, field
from typing import List, Optional

from .assets import Asset, KIND_SPRITE, KIND_TILEMAP, KIND_AUDIO, ProjectAssets
from .animation import read_anim as _read_anim_for_scan


CONFIG_FILENAME = "project.t8p"
DIR_SRC         = "src"
DIR_ASSETS      = "assets"
DIR_GENERATED   = "generated"

DEFAULT_FQBN    = "arduino:avr:uno"
DEFAULT_BOARD   = "uno"
DEFAULT_BUILD   = "arduino-cli compile --fqbn {fqbn} --build-path {build_path} {sketch}"

STARTER_SKETCH = '''// {name} -- generated by Tiny8 Studio.
// Edit src/ and assets/ in the studio, then run Build.

#include "tiny8_engine.h"

namespace t8 {{
static Framebuffer fb;
static StepClock   clk;

void setup() {{
    // TODO: register your display, init audio, etc.
    fb_init(fb);
    stepclock_init(clk, 16);
}}

void loop() {{
    uint8_t n = stepclock_poll(clk);
    if (n > 0) {{
        // TODO: update + draw your game.
    }}
}}

}}  // namespace t8
'''


@dataclass
class ProjectConfig:
    name:        str = "Tiny8Game"
    board:       str = DEFAULT_BOARD
    fqbn:        str = DEFAULT_FQBN
    build_cmd:   str = DEFAULT_BUILD
    build_path:  str = "build"   # relative to project root
    sketch:      str = "src/main.ino"
    extra:       dict = field(default_factory=dict)


class Project:
    """In-memory representation of a Tiny8 project on disk."""

    def __init__(self, root: str):
        self.root = os.path.abspath(root)
        self.config_path = os.path.join(self.root, CONFIG_FILENAME)
        self.config = ProjectConfig()
        self.assets = ProjectAssets(root=self.root)
        self._loaded = False

    # -- lifecycle -----------------------------------------------------

    @staticmethod
    def create(root: str, name: str) -> "Project":
        """Create a new project skeleton on disk.  Overwrites nothing."""
        root = os.path.abspath(root)
        if os.path.isdir(root) and os.listdir(root):
            raise FileExistsError(f"{root} is not empty")
        os.makedirs(os.path.join(root, DIR_SRC), exist_ok=True)
        os.makedirs(os.path.join(root, DIR_ASSETS), exist_ok=True)
        os.makedirs(os.path.join(root, DIR_GENERATED), exist_ok=True)
        cfg = ProjectConfig(name=name)
        with open(os.path.join(root, CONFIG_FILENAME), "w", encoding="utf-8") as f:
            json.dump(asdict(cfg), f, indent=2)
        with open(os.path.join(root, DIR_SRC, "main.ino"), "w", encoding="utf-8") as f:
            f.write(STARTER_SKETCH.format(name=name))
        p = Project(root)
        p.load()
        return p

    def load(self) -> None:
        if not os.path.isfile(self.config_path):
            raise FileNotFoundError(self.config_path)
        with open(self.config_path, "r", encoding="utf-8") as f:
            data = json.load(f)
        # Tolerate missing fields.
        conf = ProjectConfig()
        for k, v in data.items():
            if hasattr(conf, k):
                setattr(conf, k, v)
            else:
                conf.extra[k] = v
        self.config = conf
        self._scan_assets()
        self._loaded = True

    def save(self) -> None:
        with open(self.config_path, "w", encoding="utf-8") as f:
            json.dump(asdict(self.config), f, indent=2)

    # -- scanning ------------------------------------------------------

    def _scan_assets(self) -> None:
        """Walk the project's asset folders and rebuild the registry."""
        self.assets = ProjectAssets(root=self.root)
        assets_dir = os.path.join(self.root, DIR_ASSETS)
        if not os.path.isdir(assets_dir):
            return
        # Build a set of paths that are part of a multi-layer tilemap.
        # A multi-layer tilemap base is "<name>.pbm" with at least one
        # sibling "<name>_L<n>.pbm".  We surface the base as a single
        # KIND_TILEMAP asset and skip the per-layer PBMs in the
        # browser.
        seen_in_layer: set = set()
        layer_bases: dict = {}  # base_name -> list of layer indices
        for fn in sorted(os.listdir(assets_dir)):
            if not fn.lower().endswith(".pbm"):
                continue
            stem, _ = os.path.splitext(fn)
            for i in range(4):
                suffix = f"_L{i}"
                if stem.endswith(suffix):
                    base = stem[: -len(suffix)]
                    layer_bases.setdefault(base, []).append(i)
                    seen_in_layer.add(fn)
                    break
        # Animation json files.  We parse them so the Flash cost is
        # accurate in the browser.
        for fn in sorted(os.listdir(assets_dir)):
            if not fn.lower().endswith(".anim.json"):
                continue
            full = os.path.join(assets_dir, fn)
            rel = os.path.relpath(full, self.root)
            name, _ = os.path.splitext(os.path.splitext(fn)[0])
            try:
                a = _read_anim_for_scan(full)
                meta = {
                    "atlas":  a.atlas,
                    "fw":     a.frame_w,
                    "fh":     a.frame_h,
                    "ticks":  a.ticks_per_frame,
                    "loop":   a.loop,
                    "frames": len(a.frames),
                }
            except Exception:
                meta = {}
            self.assets.add(Asset(
                kind="anim", name=name, relpath=rel, meta=meta,
            ))
        # Walk PBMs.
        for fn in sorted(os.listdir(assets_dir)):
            full = os.path.join(assets_dir, fn)
            if not os.path.isfile(full):
                continue
            rel = os.path.relpath(full, self.root)
            name, ext = os.path.splitext(fn)
            if ext.lower() == ".pbm":
                if fn in seen_in_layer:
                    continue
                # Is this a multi-layer tilemap base?
                if name in layer_bases:
                    layers = layer_bases[name]
                    # Use the first layer for size metadata.
                    first = os.path.join(assets_dir,
                                          f"{name}_L{layers[0]}.pbm")
                    try:
                        w, h = _pbm_size(first)
                    except Exception:
                        w, h = 0, 0
                    # Total bytes = sum of tile counts per layer.
                    total = 0
                    for li in layers:
                        lp = os.path.join(assets_dir, f"{name}_L{li}.pbm")
                        try:
                            lw, lh = _pbm_size(lp)
                            if lw and lh and lw % 2 == 0 and lh % 2 == 0:
                                total += (lw // 2) * (lh // 2)
                        except Exception:
                            pass
                    self.assets.add(Asset(
                        kind=KIND_TILEMAP, name=name, relpath=rel,
                        meta={"w": w // 2, "h": h // 2,
                              "src_w": w, "src_h": h,
                              "layers": layers,
                              "count": total,
                              "multilayer": True},
                    ))
                    continue
                w, h = _pbm_size(full)
                # Tilemaps are flagged by a sibling .map.txt marker file.
                if os.path.isfile(os.path.join(assets_dir, name + ".map.txt")):
                    self.assets.add(Asset(
                        kind=KIND_TILEMAP, name=name, relpath=rel,
                        meta={"w": w // 2, "h": h // 2,
                              "src_w": w, "src_h": h,
                              "count": (w // 2) * (h // 2)},
                    ))
                else:
                    self.assets.add(Asset(
                        kind=KIND_SPRITE, name=name, relpath=rel,
                        meta={"w": w, "h": h},
                    ))
            elif ext.lower() in (".h", ".cpp"):
                # Pre-generated PROGMEM header.  We don't introspect; just
                # surface it for the asset browser.
                self.assets.add(Asset(
                    kind="source", name=name, relpath=rel, meta={},
                ))
        # Generated audio in generated/audio/*.h
        gen_audio = os.path.join(self.root, DIR_GENERATED, "audio")
        if os.path.isdir(gen_audio):
            for fn in sorted(os.listdir(gen_audio)):
                full = os.path.join(gen_audio, fn)
                if os.path.isfile(full):
                    self.assets.add(Asset(
                        kind=KIND_AUDIO, name=os.path.splitext(fn)[0],
                        relpath=os.path.relpath(full, self.root),
                        meta={"bytes": os.path.getsize(full)},
                    ))

    def rescan(self) -> None:
        self._scan_assets()

    # -- build ---------------------------------------------------------

    def build(self, on_line=None) -> int:
        """Run the configured build command.  `on_line(s)` is called for
        each line of output (None for a no-op callback).

        Returns 127 if the command cannot be launched (build tool not
        found, etc.), otherwise the process return code.
        """
        on_line = on_line or (lambda s: None)
        cmd = self.config.build_cmd.format(
            fqbn=self.config.fqbn,
            build_path=os.path.join(self.root, self.config.build_path),
            sketch=os.path.join(self.root, self.config.sketch),
        )
        on_line(f"$ {cmd}")
        # Pre-check: the first whitespace-separated word must exist as
        # an executable on PATH (or be a builtin like "arduino-cli" on
        # Windows where it might be a .cmd shim).
        head = cmd.strip().split(maxsplit=1)[0]
        import shutil
        if shutil.which(head) is None:
            on_line(f"ERROR: build tool not found on PATH: {head!r}")
            return 127
        try:
            proc = subprocess.Popen(
                cmd, shell=True, cwd=self.root,
                stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
                text=True, bufsize=1,
            )
        except FileNotFoundError as e:
            on_line(f"ERROR: failed to launch build: {e}")
            return 127
        assert proc.stdout is not None
        for line in proc.stdout:
            on_line(line.rstrip("\n"))
        proc.wait()
        rc = proc.returncode
        on_line(f"-- exit {rc} --")
        return rc

    # -- file helpers --------------------------------------------------

    def relpath(self, full: str) -> str:
        return os.path.relpath(full, self.root)

    def abspath(self, rel: str) -> str:
        return os.path.normpath(os.path.join(self.root, rel))


# --- module helpers ---------------------------------------------------------

def _pbm_size(path: str) -> tuple[int, int]:
    """Read just the (w, h) header of a P4 PBM file."""
    with open(path, "rb") as f:
        f.readline()  # magic
        # Skip comments.
        line = f.readline()
        while line.startswith(b"#"):
            line = f.readline()
        w, h = (int(x) for x in line.split())
    return w, h


def find_project_root(start: str) -> Optional[str]:
    """Walk up from `start` looking for project.t8p."""
    cur = os.path.abspath(start)
    while True:
        if os.path.isfile(os.path.join(cur, CONFIG_FILENAME)):
            return cur
        parent = os.path.dirname(cur)
        if parent == cur:
            return None
        cur = parent
