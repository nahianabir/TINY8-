"""Tiny8 Studio — make a sample project for first-time users.

Run with:
    python tools/tiny8_studio/tests/make_sample_project.py [target_dir]

Creates a project skeleton with two demo sprites and a tilemap so the
GUI can be opened and explored without first authoring assets.
"""

from __future__ import annotations
import json
import os
import sys


SAMPLE_PLAYER = bytes.fromhex(
    "3C7E66663C183C00"  # 8x8 helmet + face
)
SAMPLE_COIN = bytes.fromhex(
    "003C7E7E7E7E3C00"  # 8x8 ring
)
SAMPLE_TILE = bytes.fromhex(
    "AA55AA55AA55AA55"  # 8x8 checker
)

PROJECT_TPL = {
    "name": "Sample",
    "board": "uno",
    "fqbn": "arduino:avr:uno",
    "build_cmd": "arduino-cli compile --fqbn {fqbn} --build-path {build_path} {sketch}",
    "build_path": "build",
    "sketch": "src/main.ino",
}

SKETCH_TPL = '''// {name} -- generated by Tiny8 Studio.
// Edit src/ and assets/ in the studio, then run Build.

#include "tiny8_engine.h"

namespace t8 {{
static Framebuffer fb;
static StepClock   clk;

void setup() {{
    fb_init(fb);
    stepclock_init(clk, 16);
}}

void loop() {{
    uint8_t n = stepclock_poll(clk);
    if (n > 0) {{
        // TODO: update + draw your game.
    }}
}}

}}  // namespace t8
'''


def write_pbm(path: str, w: int, h: int, bits: bytes) -> None:
    row_bytes = (w + 7) // 8
    assert len(bits) == row_bytes * h, (len(bits), row_bytes * h)
    with open(path, "wb") as f:
        f.write(f"P4\n{w} {h}\n".encode("ascii"))
        f.write(bits)


def main(target: str | None = None) -> int:
    target = target or os.path.join(os.getcwd(), "sample_project")
    if os.path.isdir(target) and os.listdir(target):
        print(f"refusing: {target} is not empty", file=sys.stderr)
        return 2
    name = os.path.basename(os.path.normpath(target)) or "Sample"
    os.makedirs(os.path.join(target, "src"), exist_ok=True)
    os.makedirs(os.path.join(target, "assets"), exist_ok=True)
    os.makedirs(os.path.join(target, "generated"), exist_ok=True)
    cfg = dict(PROJECT_TPL)
    cfg["name"] = name
    with open(os.path.join(target, "project.t8p"), "w", encoding="utf-8") as f:
        json.dump(cfg, f, indent=2)
    with open(os.path.join(target, "src", "main.ino"), "w", encoding="utf-8") as f:
        f.write(SKETCH_TPL.format(name=name))
    assets = os.path.join(target, "assets")
    write_pbm(os.path.join(assets, "player.pbm"), 8, 8, SAMPLE_PLAYER)
    write_pbm(os.path.join(assets, "coin.pbm"),   8, 8, SAMPLE_COIN)
    write_pbm(os.path.join(assets, "tile.pbm"),   8, 8, SAMPLE_TILE)
    # 4x2 tilemap -> 8x4 px source.
    grid = [[0, 1, 1, 0], [0, 0, 0, 0]]
    src = bytearray()
    for row in grid:
        for _ in range(2):
            bits = []
            for t in row:
                bits += [1 if t else 0, 1 if t else 0]
            byte = 0
            for i, b in enumerate(bits):
                if b:
                    byte |= 0x80 >> i
            src.append(byte)
    write_pbm(os.path.join(assets, "level.pbm"), 8, 4, bytes(src))
    with open(os.path.join(assets, "level.map.txt"), "w", encoding="utf-8") as f:
        f.write("tilemap\n")
    # Multi-layer example: ground + props.  Each layer is a 2x2 tilemap
    # (4x4 PBM); the editor saves the sprite, the converter
    # exports a per-layer map header.
    write_pbm(os.path.join(assets, "world.pbm"),    4, 4, bytes([0] * 4))
    write_pbm(os.path.join(assets, "world_L0.pbm"), 4, 4, bytes([0] * 4))
    with open(os.path.join(assets, "world_L0.map.txt"), "w", encoding="utf-8") as f:
        f.write("tilemap\n")
    write_pbm(os.path.join(assets, "world_L1.pbm"), 4, 4, bytes([0] * 4))
    with open(os.path.join(assets, "world_L1.map.txt"), "w", encoding="utf-8") as f:
        f.write("tilemap\n")
    # Animation: a 4-frame walk cycle referencing the player sprite
    # as the atlas.
    HERE = os.path.dirname(os.path.abspath(__file__))
    sys.path.insert(0, os.path.normpath(os.path.join(HERE, "..", "..")))
    from tiny8_studio import animation as studio_anim  # type: ignore
    walk = studio_anim.Anim(
        name="walk", atlas="player", frame_w=8, frame_h=8,
        ticks_per_frame=4, loop=True, frames=[0, 0, 0, 0],
    )
    studio_anim.write_anim(os.path.join(assets, "walk.anim.json"), walk)
    print(f"created {target}")
    return 0


if __name__ == "__main__":
    args = sys.argv[1:]
    raise SystemExit(main(args[0] if args else None))
