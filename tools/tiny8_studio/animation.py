"""Tiny8 Studio — animation file format and C++ emitter.

The engine's `t8::Anim` is a small struct in PROGMEM:

    struct Anim {
        const Sprite* atlas;
        const uint8_t* frames;     // PROGMEM
        uint8_t count;
        uint8_t ticks_per_frame;
        bool loop;
    };

The studio stores an animation in a JSON file with the same fields
plus the atlas name.  At build time we emit a C++ header that
materialises the struct against an existing sprite header.  We do not
fork the C++ format — we just write the same `k{Name}Anim` and
`k{Name}AnimFrames[]` that the engine already supports.

File format (assets/<name>.anim.json):

    {
      "version": 1,
      "atlas": "<name of the sprite header, e.g. 'player_atlas'>",
      "frame_w": 8,
      "frame_h": 8,
      "ticks_per_frame": 6,
      "loop": true,
      "frames": [0, 1, 2, 1]
    }

The atlas name must match a generated sprite header.  The studio's
project scanner picks `.anim.json` files up and lists them in the
asset browser as `kind == "anim"`.
"""

from __future__ import annotations
import json
import os
from dataclasses import dataclass, field
from typing import List


ANIM_VERSION = 1


@dataclass
class Anim:
    name:            str                  # basename without extension
    atlas:           str = ""             # name of the sprite header to use
    frame_w:         int = 8
    frame_h:         int = 8
    ticks_per_frame: int = 6
    loop:            bool = True
    frames:          List[int] = field(default_factory=list)

    def to_json(self) -> dict:
        return {
            "version":          ANIM_VERSION,
            "atlas":            self.atlas,
            "frame_w":          self.frame_w,
            "frame_h":          self.frame_h,
            "ticks_per_frame":  self.ticks_per_frame,
            "loop":             self.loop,
            "frames":           list(self.frames),
        }

    def flash_bytes(self) -> int:
        """Each frame index is 1 B; the struct itself is part of the
        C++ runtime, but for the budget we just count the frame list.
        """
        return len(self.frames)


def write_anim(path: str, anim: Anim) -> None:
    """Write an animation to a .anim.json file."""
    payload = anim.to_json()
    with open(path, "w", encoding="utf-8") as f:
        json.dump(payload, f, indent=2)


def read_anim(path: str) -> Anim:
    """Read a .anim.json file.  Raises ValueError on bad input."""
    with open(path, "r", encoding="utf-8") as f:
        data = json.load(f)
    if int(data.get("version", 0)) != ANIM_VERSION:
        raise ValueError(
            f"unsupported anim version {data.get('version')} (expected "
            f"{ANIM_VERSION})")
    # The file is `<name>.anim.json`; strip both extensions to get
    # the symbol name.
    name = os.path.basename(path)
    if name.endswith(".anim.json"):
        name = name[: -len(".anim.json")]
    elif name.endswith(".json"):
        name = name[: -len(".json")]
    return Anim(
        name             = name,
        atlas            = str(data.get("atlas", "")),
        frame_w          = int(data.get("frame_w", 8)),
        frame_h          = int(data.get("frame_h", 8)),
        ticks_per_frame  = int(data.get("ticks_per_frame", 6)),
        loop             = bool(data.get("loop", True)),
        frames           = [int(x) for x in data.get("frames", [])],
    )


def write_anim_header(anim: Anim, out_path: str) -> str:
    """Emit a C++ header that defines `k{N}AnimFrames[]` and
    `k{N}Anim` matching the engine's `t8::Anim` layout.

    The user is expected to include the atlas header in their sketch
    and instantiate the player.  We do not include any other Tiny8
    headers here so the user controls the include order.
    """
    if not anim.atlas:
        raise ValueError("animation has no atlas")
    if not anim.frames:
        raise ValueError("animation has no frames")
    if not (1 <= anim.frame_w <= 32 and 1 <= anim.frame_h <= 32):
        raise ValueError(f"frame size {anim.frame_w}x{anim.frame_h} out of bounds")
    body = ", ".join(str(int(x)) for x in anim.frames)
    n = anim.name.upper()
    text = f"""// Auto-generated by Tiny8 Studio animation emitter.  Do not edit.
#ifndef TINY8_ANIM_{n}_H
#define TINY8_ANIM_{n}_H

#include <stdint.h>
#ifdef __AVR__
#include <avr/pgmspace.h>
#endif
#include "tiny8_anim.h"
#include "{anim.atlas}.h"

namespace t8 {{

constexpr uint8_t  k{n}_FrameW     = {anim.frame_w};
constexpr uint8_t  k{n}_FrameH     = {anim.frame_h};
constexpr uint8_t  k{n}_Ticks      = {anim.ticks_per_frame};
constexpr bool     k{n}_Loop       = {"true" if anim.loop else "false"};
constexpr uint8_t  k{n}_FrameCount = {len(anim.frames)};

#ifdef __AVR__
const uint8_t k{n}_Frames[] PROGMEM = {{
  {body}
}};
#else
const uint8_t k{n}_Frames[] = {{
  {body}
}};
#endif

const Anim k{n}_Anim = {{
  /* atlas           = */ &k{anim.atlas.upper()}_SPRITE,
  /* frames          = */ k{n}_Frames,
  /* count           = */ k{n}_FrameCount,
  /* ticks_per_frame = */ k{n}_Ticks,
  /* loop            = */ k{n}_Loop,
}};

}}  // namespace t8

#endif  // TINY8_ANIM_{n}_H
"""
    with open(out_path, "w", encoding="utf-8") as f:
        f.write(text)
    return out_path
