#!/usr/bin/env python3
"""Tiny8 Engine — asset converter for PROGMEM sprites and tilemaps.

Inputs:
  * PBM (binary, P4) — 1 bit per pixel.  This is the only supported input
    format because it is lossless, 1bpp, and trivially parsed without any
    image library.
    To convert PNG/JPG/etc -> PBM:
        magick assets/foo.png -monochrome -compress none assets/foo.pbm
        # or with dithering off:
        magick assets/foo.png -threshold 50% -compress none assets/foo.pbm

Outputs:
  * One C++ header (.h) per asset declaring a constexpr byte array in
    `namespace t8` suitable for `PROGMEM` placement on AVR. The header
    also exposes a ready-to-use `Sprite` instance.

Usage:
    python tools/sprite_convert.py INPUT [INPUT ...] --out generated/
    python tools/sprite_convert.py player.pbm --name player --out gen/

Constraints enforced (matching the engine spec in docs/ARCHITECTURE.md):
  * Sprite width/height  <= 32.
  * Sprite bytes         per asset <= 28 672 B (28 KB — Uno user-Flash budget).

Sprite-sheet / tilemap formats (see docs/API.md §Assets):
  * Single sprite: one input file -> one header. The header exposes
      k{N}W, k{N}H, k{N}Stride, k{N}Bits[]. Bits are MSB-first within each
      byte, row-major, rows padded to whole bytes.
  * Tilemap: invoke with --tilemap. The input is a PBM where each 2x2
      block represents one tile; the converter emits a `k{N}MapW`,
      `k{N}MapH`, and a `k{N}Tiles[]` byte array (one byte per tile,
      0 or 1).
"""

import argparse
import os
import sys
from dataclasses import dataclass
from typing import List, Tuple


# --- Limits (mirror tiny8_config.h) ---

MAX_SPRITE_W      = 32
MAX_SPRITE_H      = 32
MAX_PROGMEM_BYTES = 28 * 1024  # 28 KB user-Flash ceiling for the Uno


# --- PBM (P4) reader ---

def read_pbm(path: str) -> Tuple[int, int, List[int]]:
    with open(path, "rb") as f:
        magic = f.readline().strip()
        if magic != b"P4":
            raise ValueError(f"{path}: not a P4 PBM (got {magic!r})")
        line = f.readline()
        while line.startswith(b"#"):
            line = f.readline()
        wh = line.strip().split()
        w, h = int(wh[0]), int(wh[1])
        data = f.read()
    expected = ((w + 7) // 8) * h
    if len(data) < expected:
        raise ValueError(f"{path}: truncated (got {len(data)}, need {expected})")
    return w, h, list(data[:expected])


@dataclass
class Asset:
    name: str
    w: int
    h: int
    bits: List[int]      # MSB-first, row-major, byte-padded

    @property
    def byte_count(self) -> int:
        return ((self.w + 7) // 8) * self.h


def _to_c_array(bits: List[int], cols: int = 12) -> str:
    lines = []
    for i in range(0, len(bits), cols):
        chunk = ", ".join(f"0x{b:02X}" for b in bits[i:i+cols])
        lines.append("  " + chunk + ",")
    return "\n".join(lines)


def write_sprite_header(asset: Asset, out_path: str) -> None:
    if asset.w > MAX_SPRITE_W or asset.h > MAX_SPRITE_H:
        raise ValueError(
            f"{asset.name}: sprite exceeds {MAX_SPRITE_W}x{MAX_SPRITE_H} "
            f"({asset.w}x{asset.h})"
        )
    if asset.byte_count > MAX_PROGMEM_BYTES:
        raise ValueError(
            f"{asset.name}: asset size {asset.byte_count} B exceeds "
            f"PROGMEM budget {MAX_PROGMEM_BYTES} B"
        )
    stride = (asset.w + 7) // 8
    array  = _to_c_array(asset.bits)
    n = asset.name.upper()
    # PROGMEM is AVR-only. The host test build uses ordinary const.
    text = f"""// Auto-generated by tools/sprite_convert.py. Do not edit.
#ifndef TINY8_ASSET_{n}_H
#define TINY8_ASSET_{n}_H

#include <stdint.h>
#ifdef __AVR__
#include <avr/pgmspace.h>
#endif
#include "tiny8_sprite.h"

namespace t8 {{

constexpr uint8_t  k{n}_W      = {asset.w};
constexpr uint8_t  k{n}_H      = {asset.h};
constexpr uint16_t k{n}_Stride = {stride};
constexpr uint16_t k{n}_Bytes  = {asset.byte_count};

#ifdef __AVR__
const uint8_t k{n}_Bits[] PROGMEM = {{
{array}
}};
#else
const uint8_t k{n}_Bits[] = {{
{array}
}};
#endif

const Sprite k{n}_Sprite = {{
  /* w      = */ {asset.w},
  /* h      = */ {asset.h},
  /* stride = */ {stride},
  /* bits   = */ k{n}_Bits,
}};

}}  // namespace t8

#endif  // TINY8_ASSET_{n}_H
"""
    with open(out_path, "w", encoding="utf-8") as f:
        f.write(text)


def write_tilemap_header(name: str, w: int, h: int, tile_ids: List[int], out_path: str) -> None:
    if len(tile_ids) != w * h:
        raise ValueError(f"tile_ids length {len(tile_ids)} != w*h {w*h}")
    body = _to_c_array(tile_ids, cols=16)
    n = name.upper()
    text = f"""// Auto-generated tilemap header.
#ifndef TINY8_TILEMAP_{n}_H
#define TINY8_TILEMAP_{n}_H

#include <stdint.h>
#ifdef __AVR__
#include <avr/pgmspace.h>
#endif

namespace t8 {{

constexpr uint16_t k{n}MapW = {w};
constexpr uint16_t k{n}MapH = {h};

#ifdef __AVR__
const uint8_t k{n}Tiles[] PROGMEM = {{
{body}
}};
#else
const uint8_t k{n}Tiles[] = {{
{body}
}};
#endif

}}  // namespace t8

#endif  // TINY8_TILEMAP_{n}_H
"""
    with open(out_path, "w", encoding="utf-8") as f:
        f.write(text)
    with open(out_path, "w", encoding="utf-8") as f:
        f.write(text)


def parse_args(argv: List[str]) -> argparse.Namespace:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("inputs", nargs="+", help="input .pbm files")
    p.add_argument("--out", required=True, help="output directory")
    p.add_argument("--name", action="append", help="override output basename (per input, in order)")
    p.add_argument("--tilemap", action="store_true",
                   help="treat each 2x2 block of the input as one tile "
                        "(top-left pixel = tile id 0/1)")
    p.add_argument("--manifest", help="write a manifest file listing all generated headers")
    return p.parse_args(argv)


def main(argv: List[str]) -> int:
    args = parse_args(argv)
    os.makedirs(args.out, exist_ok=True)
    names = args.name or []
    if names and len(names) != len(args.inputs):
        print("--name count must match inputs count", file=sys.stderr)
        return 2
    total_bytes = 0
    written = []
    for i, inp in enumerate(args.inputs):
        w, h, bits = read_pbm(inp)
        name = names[i] if names else os.path.splitext(os.path.basename(inp))[0]
        if args.tilemap:
            if w % 2 or h % 2:
                raise ValueError(f"{inp}: tilemap input must have even w and h")
            tw, th = w // 2, h // 2
            tile_ids = []
            for ty in range(th):
                for tx in range(tw):
                    src_x = tx * 2
                    src_y = ty * 2
                    byte_row = src_y * ((w + 7) // 8)
                    byte_idx = byte_row + (src_x >> 3)
                    bit      = 0x80 >> (src_x & 7)
                    tile_ids.append(1 if (bits[byte_idx] & bit) else 0)
            out_path = os.path.join(args.out, f"{name}_map.h")
            write_tilemap_header(name, tw, th, tile_ids, out_path)
            total_bytes += len(tile_ids)
        else:
            asset = Asset(name=name, w=w, h=h, bits=bits)
            out_path = os.path.join(args.out, f"{name}.h")
            write_sprite_header(asset, out_path)
            total_bytes += asset.byte_count
        written.append(out_path)
        print(f"  {inp:32s}  -> {out_path}")
    print(f"Total: {total_bytes} B (limit {MAX_PROGMEM_BYTES} B).")
    if total_bytes > MAX_PROGMEM_BYTES:
        print("ERROR: total exceeds PROGMEM budget.", file=sys.stderr)
        return 1
    if args.manifest:
        with open(args.manifest, "w", encoding="utf-8") as f:
            for p in written:
                f.write(p + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))